export function lookupDemoLocation(query: string): StartingLocation | null {
  const normalized = query.trim().toLowerCase();
  if (!normalized) return null;

  for (const entry of DEMO_PAN_INDIA_LOCATIONS) {
    if (
      entry.keywords.some((kw) => normalized.includes(kw) || kw.includes(normalized))
    ) {
      return entry.location;
    }
  }
  return null;
}
